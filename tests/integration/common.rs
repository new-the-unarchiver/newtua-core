//! Помощники, общие для всего тестового бинаря.
//!
//! Сюда попадает то, что иначе размножается копиями по файлам. Помощники,
//! осмысленные только внутри одного файла (`fixture()` и родня), остаются у
//! себя: изоляция по модулям, о которой говорит `integration.rs`, для них и
//! существует.

/// SHA-256 в шестнадцатеричной записи.
///
/// Сверять содержимое, а не только имена и количество записей: проверка
/// «записей столько, ошибок нет» однажды уже пропустила дефект в релиз.
///
/// Печатается вручную побайтно намеренно: у `sha2` начиная с 0.11 результат
/// больше не умеет `{:x}`, и запись `format!("{digest:x}")` не собирается.
pub fn sha256_hex(bytes: &[u8]) -> String {
    use sha2::{Digest, Sha256};

    Sha256::digest(bytes)
        .iter()
        .fold(String::with_capacity(64), |mut hex, byte| {
            use std::fmt::Write;
            let _ = write!(hex, "{byte:02x}");
            hex
        })
}
